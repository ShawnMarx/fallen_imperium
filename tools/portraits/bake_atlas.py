"""Bake every faction portrait into the game's art (0.57.0): one PNG atlas - a row per faction (in the game's own
faction keys), 24 frames of 64 x 64 across, each frame on its painted background - plus the key list the game
reads (src/ui/gen/portrait_keys.inc). Usage: python3 bake_atlas.py OUT.png KEYS.inc"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np  # noqa: E402
from PIL import Image  # noqa: E402

import pix  # noqa: E402
import portraits_all as pa  # noqa: E402

# the game's faction key -> the portrait's key (icon names)
GAME_KEY = {'lastbastion': 'bastion', 'ilyxum': 'augers', 'ltokk': 'khrask', 'myko': 'mykomentori', 'rhodun': 'zealots'}


def main(out_png, out_inc):
    rows, keys = [], []
    for k, name, group, fn in pa.ALL:
        frames = []
        for i in range(pix.FRAMES):
            p = fn(i / pix.FRAMES)
            bg = tuple(int(v) for v in p.backdrop) + (255,)
            frames.append(np.array(p.image(1, bg=bg).convert('RGB')))
        rows.append(np.concatenate(frames, axis=1))
        keys.append(GAME_KEY.get(k, k))
    atlas = np.concatenate(rows, axis=0)
    Image.fromarray(atlas).save(out_png, optimize=True)
    with open(out_inc, 'w') as f:
        f.write('// Generated by tools/portraits/bake_atlas.py - the rows of art/portraits-pc.png, in order.\n')
        f.write('static const char* const kPortraitKeys[] = {\n')
        for i in range(0, len(keys), 8):
            f.write('    ' + ' '.join('"%s",' % k for k in keys[i:i + 8]) + '\n')
        f.write('};\n')
        f.write('static const int kPortraitFrames = %d, kPortraitSize = 64, kPortraitFrameMs = %d;\n' % (pix.FRAMES, pix.FRAME_MS))
    print(out_png, atlas.shape, os.path.getsize(out_png), 'bytes;', len(keys), 'factions')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
