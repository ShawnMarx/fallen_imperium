#!/usr/bin/env python3
"""Bake the TrueType fonts into a C++ header of anti-aliased glyph bitmaps.

The game draws all text itself (no SDL_ttf), so the fonts live inside the
program. Run `make font` after changing sizes or the character set.

Font: DejaVu Sans (Bitstream Vera licence - free to embed and redistribute).
"""
import sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

FONT_DIR = Path("/usr/share/fonts/truetype/dejavu")
REGULAR = FONT_DIR / "DejaVuSans.ttf"
BOLD = FONT_DIR / "DejaVuSans-Bold.ttf"
CONDENSED = FONT_DIR / "DejaVuSansCondensed.ttf"
CONDENSED_BOLD = FONT_DIR / "DejaVuSansCondensed-Bold.ttf"
# The Lazaxian alphabet (0.57.0): the owner's font for the Obsidian's speech and the machine talk of the L1Z1X
# and the Nekro. It has only ! " ' ( ) , - . 0-9 ? A-Z a-z and the space; FONT_LAZ holds just those.
LAZAXIAN = Path(__file__).resolve().parent.parent / "assets" / "fonts" / "Lazaxian-Bold.ttf"

# name, file, pixel size
FONTS = [
    ("FONT_XS", CONDENSED, 11),
    ("FONT_SM", CONDENSED, 13),
    ("FONT_SMB", CONDENSED_BOLD, 13),
    ("FONT_MD", REGULAR, 16),
    ("FONT_MDB", BOLD, 16),
    ("FONT_LG", BOLD, 21),
    ("FONT_XL", BOLD, 34),
    ("FONT_LAZ", LAZAXIAN, 15),
]

EXTRA = [
    0x00B0, 0x00B7, 0x00D7,                  # degree, middle dot, multiply
    0x03A9,                                  # Omega (the Codex cards, 0.43.3)
    0x03B1, 0x03B2, 0x03B3, 0x03B4, 0x03B5,  # alpha beta gamma delta epsilon (wormholes)
    0x2013, 0x2014, 0x2019, 0x201C, 0x201D,  # dashes and quotes
    0x2022, 0x2026,                          # bullet, ellipsis
    0x2190, 0x2191, 0x2192, 0x2193,          # arrows
    0x25B2, 0x25B6, 0x25BC, 0x25C0,          # triangles
    0x2605, 0x2713, 0x2717,                  # star, check, cross
]
CODEPOINTS = list(range(32, 127)) + EXTRA


def lazaxian_codepoints():
    from fontTools.ttLib import TTFont
    cmap = TTFont(str(LAZAXIAN)).getBestCmap()
    return [cp for cp in CODEPOINTS if cp in cmap]


def bake(name, path, size):
    font = ImageFont.truetype(str(path), size)
    ascent, descent = font.getmetrics()
    glyphs, bitmap = [], bytearray()
    has = set(lazaxian_codepoints()) if path == LAZAXIAN else None
    for cp in CODEPOINTS:  # (the game finds ASCII by position: every font keeps all of them, in order)
        ch = chr(cp)
        if has is not None and cp not in has:  # not in the Lazaxian alphabet: an empty glyph, a space wide
            glyphs.append((cp, len(bitmap), 0, 0, 0, 0, int(round(font.getlength(" ")))))
            continue
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        adv = int(round(font.getlength(ch)))
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        off = len(bitmap)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
            bitmap += img.tobytes()
        glyphs.append((cp, off, w, h, x0, y0, adv))
    return dict(name=name, size=size, ascent=ascent, descent=descent,
                line=ascent + descent, glyphs=glyphs, bitmap=bitmap)


def emit(fonts, out):
    lines = [
        "// GENERATED by tools/gen_font.py - do not edit by hand.",
        "// DejaVu fonts: Bitstream Vera licence (free to embed/redistribute). FONT_LAZ: the owner's Lazaxian font.",
        "#pragma once",
        '#include "gfx/font.h"',
        "",
    ]
    for f in fonts:
        n = f["name"].lower()
        lines.append(f"static const uint8_t {n}_bits[{max(1, len(f['bitmap']))}] = {{")
        b = f["bitmap"] or b"\0"
        for i in range(0, len(b), 32):
            lines.append("  " + ",".join(str(v) for v in b[i:i + 32]) + ",")
        lines.append("};")
        lines.append(f"static const GlyphInfo {n}_glyphs[{len(f['glyphs'])}] = {{")
        for cp, off, w, h, xo, yo, adv in f["glyphs"]:
            lines.append(f"  {{{cp},{off},{w},{h},{xo},{yo},{adv}}},")
        lines.append("};")
        lines.append(
            f"const FontData {f['name']} = {{{f['size']},{f['ascent']},{f['line']},"
            f"{len(f['glyphs'])},{n}_glyphs,{n}_bits}};")
        lines.append("")
    Path(out).write_text("\n".join(lines))


if __name__ == "__main__":
    out = sys.argv[1] if len(sys.argv) > 1 else "src/gfx/font_data.inc"
    baked = [bake(*spec) for spec in FONTS]
    emit(baked, out)
    total = sum(len(f["bitmap"]) for f in baked)
    print(f"wrote {out}: {len(baked)} fonts, {len(CODEPOINTS)} glyphs each, {total} bytes of bitmaps")
