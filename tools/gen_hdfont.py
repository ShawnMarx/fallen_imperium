#!/usr/bin/env python3
"""The fonts for the sharp PC picture (0.27.0).

The game's text is normally drawn from the bitmap fonts in font_data.inc
(tools/gen_font.py), made for the 640x480 screen. The Windows and Steam Deck
versions can draw the picture at the monitor's own resolution; their text is
then rasterised at run time (stb_truetype) from the same DejaVu fonts,
cut down to the characters the game uses. Output: src/gfx/hdfont_data.inc.

Font: DejaVu Sans (Bitstream Vera licence - free to embed and redistribute).
"""
import io
import sys
from fontTools import subset
from fontTools.ttLib import TTFont

sys.path.insert(0, __file__.rsplit("/", 1)[0])
import gen_font as G  # noqa: E402  (the same fonts and characters)

FILES = [("REGULAR", G.REGULAR), ("BOLD", G.BOLD), ("CONDENSED", G.CONDENSED), ("CONDENSED_BOLD", G.CONDENSED_BOLD)]


def cut(path):
    font = TTFont(str(path))
    opts = subset.Options()
    opts.hinting = False
    opts.layout_features = []
    opts.name_IDs = [0, 1, 2, 3, 4, 5, 6]  # keep the copyright and licence names
    opts.notdef_outline = True
    s = subset.Subsetter(opts)
    s.populate(unicodes=G.CODEPOINTS)
    s.subset(font)
    out = io.BytesIO()
    font.save(out)
    return out.getvalue()


def main(out_path):
    with open(out_path, "w") as f:
        f.write("// Generated by tools/gen_hdfont.py - DejaVu Sans subsets (Bitstream Vera licence) + the owner's Lazaxian font.\n")
        for name, path in FILES + [("LAZAXIAN", G.LAZAXIAN)]:
            data = cut(path) if path != G.LAZAXIAN else open(path, "rb").read()
            f.write("static const unsigned char kTtf%s[%d] = {\n" % (name.title().replace("_", ""), len(data)))
            for i in range(0, len(data), 24):
                f.write("    " + ",".join(str(b) for b in data[i:i + 24]) + ",\n")
            f.write("};\n")
            print(name, len(data), "bytes")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "src/gfx/hdfont_data.inc")
