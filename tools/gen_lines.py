#!/usr/bin/env python3
"""The negotiation lines (0.57.0): tools/lines/*.txt -> src/ui/gen/lines.inc.

Each faction section ([key]) holds `name:` (how others address it), `voice:` (for the owner) and its lines by
category; `[pair speaker > listener]` sections hold lines one faction says only to another (rivals, kin), used
before the generic ones. {them} = the listener's name. See tools/lines/BRIEF.md for the writing rules.
Usage: python3 tools/gen_lines.py tools/lines src/ui/gen/lines.inc"""
import glob
import os
import re
import sys

CATS = ['offer', 'friendly', 'threat', 'vote', 'accept', 'decline', 'counter', 'betray', 'betrayed']
LAZ_OK = set("ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789 !\"'(),-.?")


def parse(folder):
    factions, pairs, problems = {}, [], []
    for path in sorted(glob.glob(os.path.join(folder, '*.txt'))):
        cur = None
        for n, raw in enumerate(open(path, encoding='utf-8'), 1):
            line = raw.rstrip('\n').strip()
            if not line or line.startswith('#'):
                continue
            m = re.match(r'^\[pair\s+([a-z0-9]+)\s*>\s*([a-z0-9]+)\]$', line)
            if m:
                cur = ('pair', m.group(1), m.group(2))
                continue
            m = re.match(r'^\[([a-z0-9]+)\]$', line)
            if m:
                cur = ('faction', m.group(1))
                factions.setdefault(m.group(1), {'name': '', 'voice': '', 'lines': {c: [] for c in CATS}, 'file': path})
                continue
            m = re.match(r'^([a-z]+):\s*(.*)$', line)
            if not m or cur is None:
                problems.append('%s:%d: not understood: %s' % (path, n, line))
                continue
            field, text = m.group(1), m.group(2).strip()
            if cur[0] == 'faction':
                f = factions[cur[1]]
                if field in ('name', 'voice'):
                    f[field] = text
                elif field in CATS:
                    f['lines'][field].append(text)
                else:
                    problems.append('%s:%d: unknown field %s' % (path, n, field))
            else:
                if field in CATS:
                    pairs.append((cur[1], cur[2], field, text))
                else:
                    problems.append('%s:%d: unknown field %s' % (path, n, field))
    return factions, pairs, problems


def check(key, cat, text, problems, where):
    t = text.replace('{them}', 'x' * 12)
    if len(t) > 175:
        problems.append('%s: %s %s is %d characters long' % (where, key, cat, len(t)))
    if key == 'nekro' and not re.match(r"^[A-Za-z'-]+ \| [A-Za-z'-]+[.!?]?$", text):
        problems.append('%s: nekro %s is not "Word | Word": %s' % (where, cat, text))
    if key == 'ghemina' and '||' not in text:
        problems.append('%s: ghemina %s has no ||: %s' % (where, cat, text))
    if key == 'obsidian':
        bad = set(text.replace('{them}', '')) - LAZ_OK
        if bad:
            problems.append('%s: obsidian %s uses %s' % (where, cat, ''.join(sorted(bad))))
    if cat in ('betray', 'betrayed') and '{them}' not in text and key != 'nekro' and not where.startswith('pairs'):
        # (Nekro: two words only; a pair line may name the other side itself)
        problems.append('%s: %s %s does not name {them}' % (where, key, cat))
    if any(ord(ch) > 126 for ch in text):
        problems.append('%s: %s %s has a non-ASCII character: %s' % (where, key, cat, text))


def esc(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main(folder, out):
    factions, pairs, problems = parse(folder)
    for key, f in factions.items():
        if not f['name']:
            problems.append('%s: no name' % key)
        for cat in CATS:
            if not f['lines'][cat]:
                problems.append('%s: no %s line' % (key, cat))
            for t in f['lines'][cat]:
                check(key, cat, t, problems, os.path.basename(f['file']))
    for s, l, cat, t in pairs:
        check(s, cat, t, problems, 'pairs %s>%s' % (s, l))
        for k in (s, l):
            if k not in factions:
                problems.append('pair %s>%s: unknown faction %s' % (s, l, k))
    with open(out, 'w') as o:
        o.write('// Generated by tools/gen_lines.py from tools/lines/*.txt - do not edit.\n')
        o.write('static const SpeechName kSpeechNames[] = {\n')
        for key in sorted(factions):
            o.write('    {%s, %s},\n' % (esc(key), esc(factions[key]['name'])))
        o.write('};\n')
        o.write('static const SpeechLine kSpeechLines[] = {\n')
        for key in sorted(factions):
            for ci, cat in enumerate(CATS):
                for t in factions[key]['lines'][cat]:
                    o.write('    {%s, nullptr, %d, %s},\n' % (esc(key), ci, esc(t)))
        for s, l, cat, t in pairs:
            o.write('    {%s, %s, %d, %s},\n' % (esc(s), esc(l), CATS.index(cat), esc(t)))
        o.write('};\n')
    n = sum(len(v) for f in factions.values() for v in f['lines'].values())
    print('%s: %d factions, %d lines, %d pair lines' % (out, len(factions), n, len(pairs)))
    for p in problems:
        print('  PROBLEM', p)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1], sys.argv[2]))
